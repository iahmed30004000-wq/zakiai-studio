"""أخطاء الطبقة — كل الرسائل بالعربي البسيط وجاهزة للعرض."""


class JobError(Exception):
    """مشكلة ببناء المهمة (خط زمني ناقص، ملف ناقص، مسار ممنوع…)."""


class StageError(Exception):
    """مشكلة بتجهيز ملفات الوسائط لمجلد العمل."""


class RendererUnavailable(Exception):
    """ما في محرّك رندر جاهز بهالاسم."""


class RenderError(Exception):
    """فشل الرندر (Node/المتصفح ناقص، أو المحرّك وقع، أو المهلة خلصت…) — الرسالة عربية جاهزة للعرض."""
